const road = (from: string, to: string): Leg => ({
  mode: Mode.Road,
  from,
  to,
  operator: "Roadline",
});
const sea = (from: string, to: string): Leg => ({
  mode: Mode.Sea,
  from,
  to,
  operator: "OceanSpan",
});
const customs = (at: string): Leg => ({
  mode: Mode.Customs,
  from: at,
  to: at,
  operator: "OceanSpan",
});

const event = (
  id: string,
  operator: OperatorEvent["operator"],
  code: string,
  description: string,
  occurredAt: string,
  leg: number,
  receivedAt = occurredAt,
): OperatorEvent => ({
  id,
  operator,
  code,
  description,
  occurredAt,
  receivedAt,
  leg,
});

